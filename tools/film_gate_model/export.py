"""Write the verifier and box scorer weights as Rust constants for src/film_border.rs.

  python export.py <verifier.pt> ../../src/film_border_verifier_weights.rs

The box scorer ensemble is read from box_scorer_<fold>.pt next to verifier_<fold>.pt.
"""
import os
import sys

import torch


def rust_array(name, tensor):
    values = tensor.detach().cpu().reshape(-1).tolist()
    body = ",\n".join(
        "    " + ", ".join("%.9e" % v for v in values[i:i + 6]) for i in range(0, len(values), 6)
    )
    return "const %s: [f32; %d] = [\n%s,\n];\n" % (name, len(values), body)


def main():
    state = torch.load(sys.argv[1], map_location="cpu")
    parts = [
        "// Generated by tools/film_gate_model/export.py from %s. Do not edit.\n"
        % sys.argv[1].split("/")[-1],
        rust_array("VERIFIER_C1_W", state["c1.weight"]),
        rust_array("VERIFIER_C1_B", state["c1.bias"]),
        rust_array("VERIFIER_C2_W", state["c2.weight"]),
        rust_array("VERIFIER_C2_B", state["c2.bias"]),
        rust_array("VERIFIER_C3_W", state["c3.weight"]),
        rust_array("VERIFIER_C3_B", state["c3.bias"]),
        rust_array("VERIFIER_FC_W", state["fc.weight"]),
        "const VERIFIER_FC_B: f32 = %.9e;\n" % state["fc.bias"].item(),
    ]
    folder, name = os.path.split(sys.argv[1])
    scorer = torch.load(os.path.join(folder, name.replace("verifier_", "box_scorer_", 1)), map_location="cpu")
    models = sorted({key.split(".")[0] for key in scorer})
    stack = lambda key: torch.cat([scorer["%s.%s" % (m, key)].reshape(-1) for m in models])
    c2 = [scorer["%s.c2.weight" % m] for m in models]
    width = scorer["%s.c1.weight" % models[0]].shape[0]
    parts += [
        "const BOX_SCORER_MODELS: usize = %d;\n" % len(models),
        "const BOX_SCORER_WIDTH: usize = %d;\n" % width,
        "const BOX_SCORER_HIDDEN: usize = %d;\n" % scorer["%s.f.weight" % models[0]].shape[0],
        rust_array("BOX_SCORER_C1_W", stack("c1.weight")),
        rust_array("BOX_SCORER_C1_B", stack("c1.bias")),
        rust_array("BOX_SCORER_C2_W", torch.cat([w[:, :width].reshape(-1) for w in c2])),
        rust_array("BOX_SCORER_C2_MASK_W", torch.cat([w[:, width:].reshape(-1) for w in c2])),
        rust_array("BOX_SCORER_C2_B", stack("c2.bias")),
        rust_array("BOX_SCORER_C3_W", stack("c3.weight")),
        rust_array("BOX_SCORER_C3_B", stack("c3.bias")),
        rust_array("BOX_SCORER_C4_W", stack("c4.weight")),
        rust_array("BOX_SCORER_C4_B", stack("c4.bias")),
        rust_array("BOX_SCORER_FC1_W", stack("f.weight")),
        rust_array("BOX_SCORER_FC1_B", stack("f.bias")),
        rust_array("BOX_SCORER_FC2_W", stack("o.weight")),
        rust_array("BOX_SCORER_FC2_B", stack("o.bias")),
    ]
    open(sys.argv[2], "w").write("\n".join(parts))


if __name__ == "__main__":
    main()
