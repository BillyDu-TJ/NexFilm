    let locale = localStorage.getItem('nexfilm-language') || 'en';
    if (!dictionaries[locale]) locale = 'en';
    const listeners = new Set();
    const sourceByNode = new WeakMap();

    function interpolate(value, vars = {}) {
        return String(value).replace(/\{(\w+)\}/g, (_, key) => vars[key] === undefined ? `{${key}}` : String(vars[key]));
    }

    function t(key, vars = {}) {
        const value = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
        return interpolate(value, vars);
    }

    function translateLegacy(message) {
        const source = String(message ?? '');
        const key = legacyText[source.trim()];
        if (key) return t(key);
        for (const [pattern, patternKey, variable] of legacyPatterns) {
            const match = source.match(pattern);
            if (match) {
                const vars = {};
                if (variable === 'count') vars.count = match[1];
                else if (variable) vars[variable] = match[1];
                return t(patternKey, vars);
            }
        }
        return source;
    }

    function applyAttributes(root) {
        root.querySelectorAll('[data-i18n]').forEach(element => {
            const value = t(element.dataset.i18n, element.dataset.i18nVars ? JSON.parse(element.dataset.i18nVars) : {});
            const attribute = element.dataset.i18nAttr || 'textContent';
            if (attribute === 'textContent') element.textContent = value;
            else element.setAttribute(attribute, value);
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach(element => element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder)));
        root.querySelectorAll('[data-i18n-title]').forEach(element => element.setAttribute('title', t(element.dataset.i18nTitle)));
        root.querySelectorAll('[data-i18n-aria-label]').forEach(element => element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel)));
        root.querySelectorAll('[data-i18n-alt]').forEach(element => element.setAttribute('alt', t(element.dataset.i18nAlt)));
        root.querySelectorAll('[label]').forEach(element => {
            const source = element.dataset.i18nLabelSource || element.getAttribute('label');
            const key = legacyText[source];
            if (!key) return;
            element.dataset.i18nLabelSource = source;
            element.setAttribute('label', t(key));
        });
    }

    function applyLegacyText(root) {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        const nodes = [];
        let node;
        while ((node = walker.nextNode())) nodes.push(node);
        nodes.forEach(textNode => {
            if (textNode.parentElement?.closest('script,style,template')) return;
            const original = sourceByNode.get(textNode) ?? textNode.nodeValue;
            const trimmed = original.trim();
            const key = legacyText[trimmed];
            if (!key) {
                if (!sourceByNode.has(textNode)) sourceByNode.set(textNode, original);
                return;
            }
            if (!sourceByNode.has(textNode)) sourceByNode.set(textNode, original);
            const leading = original.slice(0, original.indexOf(trimmed));
            const trailing = original.slice(original.indexOf(trimmed) + trimmed.length);
            textNode.nodeValue = leading + t(key) + trailing;
        });
    }

    function apply(root = document) {
        applyAttributes(root);
        applyLegacyText(root);
        document.documentElement.lang = locale === 'zh-CN' ? 'zh-CN' : 'en';
        if (document.body) document.body.dataset.locale = locale;
        document.title = t('app.title');
    }

    function setLocale(nextLocale) {
        const next = dictionaries[nextLocale] ? nextLocale : 'en';
        if (next === locale) {
            apply();
            return;
        }
        locale = next;
        localStorage.setItem('nexfilm-language', locale);
        apply();
        listeners.forEach(listener => listener(locale));
    }

    function onChange(listener) {
        listeners.add(listener);
        return () => listeners.delete(listener);
    }

    window.NexFilmI18n = {
        t,
        translateLegacy,
        apply,
        setLocale,
        getLocale: () => locale,
        onChange,
    };

    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => apply(), { once: true });
    else apply();
